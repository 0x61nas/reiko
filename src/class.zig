pub const ConstantPool = struct {
    pool: std.ArrayList(ConstantInfo),

    pub inline fn initCapacity(allocator: anytype, size: usize) !ConstantPool {
        return .{ .pool = try std.ArrayList(ConstantInfo).initCapacity(allocator, size) };
    }

    pub inline fn appendAssumeCapacity(me: *ConstantPool, item: ConstantInfo) void {
        me.pool.appendAssumeCapacity(item);
    }

    pub inline fn items(me: *const ConstantPool) []ConstantInfo {
        return me.pool.items;
    }

    pub inline fn at(me: *const ConstantPool, idx: u16) ConstantInfo {
        // if (idx == 0 or idx - 1 > me.pool.items.len) return error.ConstantIndexOutsideRange;
        return me.pool.items[idx - 1];
    }
    pub inline fn at_checked(me: *const ConstantPool, idx: u16) !ConstantInfo {
        if (idx == 0 or idx - 1 > me.pool.items.len) return error.ConstantIndexOutsideRange;
        return me.pool.items[idx - 1];
    }

    pub inline fn deinit(me: @This()) void {
        me.pool.deinit();
    }
};

/// Constant pool table entry. (§4.4)
pub const ConstantInfo = union(ConstantInfo.Tag) {
    // tag: ConstantTag,
    // info: []const u8,
    class: struct {
        name_index: u16,

        pub inline fn resolve_idx(me: @This(), constant_pool: *const ConstantPool) []const u8 {
            // if (idx == 0 or idx - 1 > me.pool.items.len) return error.ConstantIndexOutsideRange;
            return constant_pool.at(me.name_index).utf8.bytes;
        }
    },
    fieldref: RefInfo,
    methodref: RefInfo,
    interface_methodref: RefInfo,
    string: struct {
        string_index: u16,
    },
    integer: Number4Bytes,
    float: Number4Bytes,
    long: Number8Bytes,
    double: Number8Bytes,
    name_and_type: NameAndType,
    utf8: struct {
        // length: u16,
        bytes: []const u8,

        pub fn len(me: @This()) u16 {
            return @as(u16, me.bytes.len);
        }
    },
    method_handle: struct {
        refrence_kind: MethodRefKind,
        refrence_index: u16,
    },
    method_type: struct {
        descriptor_index: u16,
    },
    dynamic: DynamicInfoConst,
    invoke_dynamic: DynamicInfoConst,
    module: struct {
        name_index: u16,
    },
    package: struct {
        name_index: u16,
    },

    pub const Tag = enum(u8) {
        class = 7, // §4.4.1
        fieldref = 9, // §4.4.2
        methodref = 10, // §4.4.2
        interface_methodref = 11, // §4.4.2
        string = 8, //§4.4.3
        integer = 3, //§4.4.4
        float = 4, //§4.4.4
        long = 5, //§4.4.5
        double = 6, //§4.4.5
        name_and_type = 12, // §4.4.6
        utf8 = 1, //§4.4.7
        method_handle = 15, // §4.4.8
        method_type = 16, // §4.4.9
        dynamic = 17, // §4.4.10
        invoke_dynamic = 18, // §4.4.10
        module = 19, // §4.4.11
        package = 20, // §4.4.12

        fn from_u8(v: u8) !Tag {
            inline for (@typeInfo(@This()).@"enum".fields) |f| {
                if (f.value == v) return @field(@This(), f.name);
            }
            return error.InvalidConstantTag;
        }
    };

    /// Bytecode Behaviors for Method Handles (Table 5.4.3.5-A)
    pub const MethodRefKind = enum(u8) {
        REF_getField = 1, // getfield C.f:T
        REF_getStatic = 2, // getstatic C.f:T
        REF_putField = 3, // putfield C.f:T
        REF_putStatic = 4, // putstatic C.f:T
        REF_invokeVirtual = 5, // invokevirtual C.m:(A*)T
        REF_invokeStatic = 6, // invokestatic C.m:(A*)T
        REF_invokeSpecial = 7, // invokespecial C.m:(A*)T
        REF_newInvokeSpecial = 8, // new C; dup; invokespecial C.<init>:(A*)V
        REF_invokeInterface = 9, // invokeinterface C.m:(A*)T

        inline fn from_u8(v: u8) !MethodRefKind {
            if (v == 0 or v > 9) return error.InvalidMethodRefKind;
            return @enumFromInt(v);
        }
    };

    pub const RefInfo = struct {
        class_index: u16,
        name_and_type_index: u16,

        pub fn resolve_class_idx(me: @This(), constant_pool: *const ConstantPool) []const u8 {
            return constant_pool.at(me.class_index).class.resolve_idx(constant_pool);
        }

        pub inline fn resolve_name_and_typ_idx(me: @This(), constant_pool: *const ConstantPool) NameAndType {
            return constant_pool.at(me.name_and_type_index).name_and_type;
        }
    };

    pub const NameAndType = struct {
        name_index: u16,
        descriptor_index: u16,

        pub inline fn resolve_name_idx(me: @This(), constant_pool: *const ConstantPool) []const u8 {
            return constant_pool.at(me.name_index).utf8.bytes;
        }

        pub inline fn resolve_descriptor_idx(me: @This(), constant_pool: *const ConstantPool) []const u8 {
            return constant_pool.at(me.descriptor_index).utf8.bytes;
        }
    };

    pub const Number4Bytes = struct {
        bytes: u32,
    };

    pub const Number8Bytes = union {
        high_bytes: u32,
        low_bytes: u32,
    };

    pub const DynamicInfoConst = struct {
        bootstrap_method_attr_index: u16,
        name_and_type_index: u16,
    };
};

