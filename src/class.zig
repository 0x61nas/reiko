    pub const TargetPath = struct {
        // u1 path_length;
        path: []PathEntry,

        pub const PathEntry = packed struct {
            type_path_kind: u8,
            type_argument_index: u8,
        };
    };

    pub const ElementValuePair = struct {
        element_name_index: u16,
        value: ElementValue,

        pub const ElementValue = struct {
            tag: Tag,
            value: Value,

            pub const Tag = enum(u8) {
                Byte = 'B',
                Char = 'C',
                Double = 'D',
                Float = 'F',
                Int = 'I',
                Long = 'J',
                Short = 'S',
                Boolean = 'Z',
                String = 's',
                Enum = 'e',
                Class = 'c',
                Annotation = '@',
                Array = '[',

                fn from_u8(v: u8) !Tag {
                    inline for (@typeInfo(@This()).@"enum".fields) |f| {
                        if (f.value == v) return @field(@This(), f.name);
                    }
                    return error.InvalidElementValueTag;
                }
            };

            pub const Value = union {
                const_value_index: u16,

                enum_const_value: struct {
                    type_name_index: u16,
                    const_name_index: u16,
                },

                class_info_index: u16,

                // TODO(anas): re-check this
                annotation: Annotation,

                array_value: struct {
                    // num_values: u16,
                    values: []ElementValue,
                },
            };
        };
    };
};

pub const VerificationTypeInfo = union(VerificationTypeInfo.Tag) {
    Top_variable_info: void,
    Integer_variable_info: void,
    Float_variable_info: void,
    Long_variable_info: void,
    Double_variable_info: void,
    Null_variable_info: void,
    UninitializedThis_variable_info: void,
    Object_variable_info: struct {
        cpool_index: u16,
    },
    Uninitialized_variable_info: struct {
        offset: u16,
    },

    pub const Tag = enum(u8) {
        Top_variable_info = 0,
        Integer_variable_info = 1,
        Float_variable_info = 2,
        Long_variable_info = 4,
        Double_variable_info = 3,
        Null_variable_info = 5,
        UninitializedThis_variable_info = 6,
        Object_variable_info = 7,
        Uninitialized_variable_info = 8,

        pub inline fn from_u8(v: u8) !@This() {
            if (v < 9) {
                return @enumFromInt(v);
            }
            return error.InvalidVerificationInfoTag;
        }
    };
};
